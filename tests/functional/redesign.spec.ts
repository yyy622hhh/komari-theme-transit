import { expect, test } from '@playwright/test'
import { installKomariFixture } from '../visual/fixtures/komari'

test('partial return-route results stay in their carrier columns', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await installKomariFixture(page, { opsDashboard: true, returnRouteTag: 'partial' })
  await page.goto('/')
  const card = page.locator('[data-transit-node-card-size]').filter({ has: page.locator('[data-node-route-panel]') }).first()
  const rows = card.locator('[data-node-route-panel] [data-carrier]')
  await expect(rows).toHaveCount(2)
  await expect(card.locator('[data-node-route-panel] [data-carrier="CU"]')).toHaveCount(0)
  for (const [carrier, column] of [['CT', 1], ['CM', 2]] as const) {
    const route = await card.locator(`[data-node-route-panel] [data-carrier="${carrier}"]`).boundingBox()
    const quality = await card.locator('[data-node-carrier-row]').nth(column).boundingBox()
    expect(route).not.toBeNull()
    expect(quality).not.toBeNull()
    expect(Math.abs(route!.x - quality!.x)).toBeLessThanOrEqual(1)
    expect(Math.abs(route!.width - quality!.width)).toBeLessThanOrEqual(1)
  }
})

